function escapeRegex(str) {
  return str.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function isUpperFirst(s) {
  return s.length > 0 && s[0] === s[0].toUpperCase() && s[0] !== s[0].toLowerCase();
}

function capitaliseFirst(s) {
  if (!s) return s;
  return s[0].toUpperCase() + s.slice(1);
}

function translatePhrase(text, table) {
  if (!text) return text;
  let out = text;
  for (const [from, to] of table) {
    // Case-insensitive RU lookup, but preserve uppercase-first when the
    // original word in the source text starts with an uppercase letter.
    const startsWithLetter = /[А-Яа-яЁё]/.test(from[0]);
    const endsWithLetter = /[А-Яа-яЁё]/.test(from[from.length - 1]);
    const left = startsWithLetter ? "(?<![А-Яа-яЁё])" : "";
    const right = endsWithLetter ? "(?![А-Яа-яЁё])" : "";
    const re = new RegExp(left + escapeRegex(from) + right, "gi");
    out = out.replace(re, (match) => (isUpperFirst(match) ? capitaliseFirst(to) : to));
  }
  return out;
}

function hasCyrillic(text) {
  return /[А-Яа-яЁё]/.test(text || "");
}

function processFile(file) {
  const raw = fs.readFileSync(file, "utf-8");
  const products = JSON.parse(raw);
  let touched = 0;

  for (const p of products) {
    // Reset any prior auto-generated translation so the script is idempotent.
    delete p.i18n;

    const fields = ["name", "shortDescription", "description"];
    const en = {};
    const zh = {};

    for (const f of fields) {
      const v = p[f];
      if (typeof v !== "string" || !v) continue;

      const enText = translatePhrase(v, RU_TO_EN);
      const zhText = translatePhrase(v, RU_TO_ZH);

      // Only emit a translation if it actually changed (otherwise the locale
      // will fall back to RU which is the same anyway).
      if (enText !== v) en[f] = enText;
      if (zhText !== v) zh[f] = zhText;
    }

    // Translate spec keys/values too — they appear inside specs[].
    if (Array.isArray(p.specs) && p.specs.length > 0) {
      const specsEn = [];
      const specsZh = [];
      let specsChanged = { en: false, zh: false };
      for (const s of p.specs) {
        const k = s.key ?? "";
        const v = s.value ?? "";
        const ek = translatePhrase(k, RU_TO_EN);
        const ev = translatePhrase(v, RU_TO_EN);
        const zk = translatePhrase(k, RU_TO_ZH);
        const zv = translatePhrase(v, RU_TO_ZH);
        specsEn.push({ key: ek, value: ev });
        specsZh.push({ key: zk, value: zv });
        if (ek !== k || ev !== v) specsChanged.en = true;
        if (zk !== k || zv !== v) specsChanged.zh = true;
      }
      if (specsChanged.en) en.specs = specsEn;
      if (specsChanged.zh) zh.specs = specsZh;
    }

    if (Object.keys(en).length === 0 && Object.keys(zh).length === 0) continue;

    p.i18n = p.i18n || {};
    if (Object.keys(en).length > 0) p.i18n.en = { ...(p.i18n.en || {}), ...en };
    if (Object.keys(zh).length > 0) p.i18n.zh = { ...(p.i18n.zh || {}), ...zh };
    touched++;
  }

  fs.writeFileSync(file, JSON.stringify(products, null, 2) + "\n", "utf-8");
  console.log(`${path.basename(file)}: translated ${touched}/${products.length} products`);
}

function main() {
  const files = fs.readdirSync(DATA_DIR).filter((f) => f.endsWith(".json"));
  for (const f of files) processFile(path.join(DATA_DIR, f));
}

